import { confirmAction } from '../utils/confirmAction.js';
﻿import { useCallback, useEffect, useState } from 'react';
import {
  ArrowDown,
  ArrowUp,
  Copy,
  Pencil,
  Plus,
  Send,
  Trash2,
} from 'lucide-react';

import {
  LEADERSHIP_TYPES,
  createLeadershipVersion,
  getLeadershipForms,
  getLeadershipVersion,
  publishLeadershipVersion,
  updateLeadershipVersion,
} from '../services/leadershipApi.js';

import {
  ErrorBanner,
  LoadingBlock,
  StatusPill,
  SuccessBanner,
  formatDate,
} from './StateBlocks.jsx';

const createEmptyForm = () => ({
  title: '',
  instructions: '',
  scaleMin: '',
  scaleMax: '',
  allowNa: false,
  criteria: [{ sectionTitle: '', text: '' }],
});

function validateForm(form) {
  if (!form.title.trim()) {
    // The title is optional in the interface and may be generated by the API.
  } else if (form.title.trim().length > 255) {
    return 'The form title cannot exceed 255 characters.';
  }

  if (form.instructions.length > 10000) {
    return 'Instructions cannot exceed 10,000 characters.';
  }

  if (form.scaleMin === '' || form.scaleMax === '') {
    return 'Enter the lowest and highest score of the scale.';
  }

  const min = Number(form.scaleMin);
  const max = Number(form.scaleMax);

  if (
    !Number.isInteger(min) ||
    !Number.isInteger(max) ||
    min < 0 ||
    max > 255
  ) {
    return 'Scale values must be whole numbers between 0 and 255.';
  }

  if (min >= max) {
    return 'The lowest score must be lower than the highest score.';
  }

  if (!form.criteria.length) {
    return 'Add at least one criterion.';
  }

  if (
    form.criteria.some(
      (criterion) => criterion.sectionTitle.trim().length > 255,
    )
  ) {
    return 'A section title cannot exceed 255 characters.';
  }

  const filledCriteria = form.criteria.filter(
    (criterion) => criterion.text.trim(),
  );

  if (!filledCriteria.length) {
    return 'Add at least one criterion.';
  }

  if (
    filledCriteria.some(
      (criterion) => criterion.text.trim().length > 600,
    )
  ) {
    return 'A criterion cannot exceed 600 characters.';
  }

  return '';
}

function toPayload(form) {
  return {
    title: form.title.trim() || undefined,
    instructions: form.instructions.trim() || null,
    scaleMin: Number(form.scaleMin),
    scaleMax: Number(form.scaleMax),
    allowNa: Boolean(form.allowNa),
    criteria: form.criteria
      .filter((criterion) => criterion.text.trim())
      .map((criterion) => ({
        sectionTitle: criterion.sectionTitle.trim() || null,
        text: criterion.text.trim(),
      })),
  };
}

function getLeadershipType(type) {
  return LEADERSHIP_TYPES[type] ?? {
    label: type,
    evaluator: 'Authorized evaluator',
    evaluatee: 'Assigned staff member',
  };
}

function Editor({
  editor,
  saving,
  onChange,
  onSave,
  onCancel,
}) {
  const { form } = editor;
  const leadershipType = getLeadershipType(editor.type);

  const setField = (key, value) => {
    onChange({ ...form, [key]: value });
  };

  const setCriterion = (index, key, value) => {
    onChange({
      ...form,
      criteria: form.criteria.map((criterion, criterionIndex) =>
        criterionIndex === index
          ? { ...criterion, [key]: value }
          : criterion,
      ),
    });
  };

  const moveCriterion = (index, delta) => {
    const target = index + delta;

    if (target < 0 || target >= form.criteria.length) {
      return;
    }

    const criteria = [...form.criteria];
    [criteria[index], criteria[target]] = [
      criteria[target],
      criteria[index],
    ];

    onChange({ ...form, criteria });
  };

  const removeCriterion = (index) => {
    onChange({
      ...form,
      criteria: form.criteria.filter(
        (_, criterionIndex) => criterionIndex !== index,
      ),
    });
  };

  const addCriterion = () => {
    onChange({
      ...form,
      criteria: [
        ...form.criteria,
        { sectionTitle: '', text: '' },
      ],
    });
  };

  return (
    <form
      className="panel-card space-y-5 p-5"
      onSubmit={(event) => {
        event.preventDefault();
        onSave();
      }}
      aria-label="Leadership evaluation form version editor"
    >
      <div>
        <h3 className="text-base font-semibold text-slate-900">
          {editor.versionId ? 'Edit draft version' : 'New draft version'}
          {' · '}
          {leadershipType.label}
        </h3>

        <p className="mt-1 text-sm text-slate-600">
          Enter the criteria and scoring scale from the approved institutional
          form. Published versions cannot be edited.
        </p>
      </div>

      <div className="grid gap-4 md:grid-cols-2">
        <label className="block text-sm">
          <span className="font-medium text-slate-700">
            Form title (optional)
          </span>
          <input
            type="text"
            maxLength={255}
            className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2"
            value={form.title}
            onChange={(event) => setField('title', event.target.value)}
          />
        </label>

        <div className="grid grid-cols-3 gap-3">
          <label className="block text-sm">
            <span className="font-medium text-slate-700">
              Lowest score
            </span>
            <input
              type="number"
              min="0"
              max="254"
              step="1"
              required
              className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2"
              value={form.scaleMin}
              onChange={(event) => setField('scaleMin', event.target.value)}
            />
          </label>

          <label className="block text-sm">
            <span className="font-medium text-slate-700">
              Highest score
            </span>
            <input
              type="number"
              min="1"
              max="255"
              step="1"
              required
              className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2"
              value={form.scaleMax}
              onChange={(event) => setField('scaleMax', event.target.value)}
            />
          </label>

          <label className="flex items-end gap-2 pb-2 text-sm font-medium text-slate-700">
            <input
              type="checkbox"
              checked={form.allowNa}
              onChange={(event) => setField('allowNa', event.target.checked)}
            />
            Allow N/A
          </label>
        </div>
      </div>

      <label className="block text-sm">
        <span className="font-medium text-slate-700">
          Instructions for the evaluator (optional)
        </span>
        <textarea
          rows={3}
          maxLength={10000}
          className="mt-1 w-full rounded-lg border border-slate-300 px-3 py-2"
          value={form.instructions}
          onChange={(event) => setField('instructions', event.target.value)}
        />
      </label>

      <fieldset className="space-y-3">
        <legend className="text-sm font-medium text-slate-700">
          Evaluation criteria, in the order the evaluator sees them
        </legend>

        {form.criteria.map((criterion, index) => (
          <div
            key={index}
            className="grid gap-2 rounded-lg border border-slate-200 p-3 md:grid-cols-[200px_minmax(0,1fr)_auto]"
          >
            <input
              type="text"
              aria-label={`Section of criterion ${index + 1}`}
              placeholder="Section (optional)"
              maxLength={255}
              className="rounded-lg border border-slate-300 px-3 py-2 text-sm"
              value={criterion.sectionTitle}
              onChange={(event) =>
                setCriterion(index, 'sectionTitle', event.target.value)
              }
            />

            <input
              type="text"
              aria-label={`Text of criterion ${index + 1}`}
              placeholder="Enter official criterion text"
              maxLength={600}
              className="rounded-lg border border-slate-300 px-3 py-2 text-sm"
              value={criterion.text}
              onChange={(event) =>
                setCriterion(index, 'text', event.target.value)
              }
            />

            <div className="flex gap-1">
              <button
                type="button"
                className="icon-button"
                aria-label={`Move criterion ${index + 1} up`}
                title="Move up"
                disabled={saving || index === 0}
                onClick={() => moveCriterion(index, -1)}
              >
                <ArrowUp size={16} />
              </button>

              <button
                type="button"
                className="icon-button"
                aria-label={`Move criterion ${index + 1} down`}
                title="Move down"
                disabled={saving || index === form.criteria.length - 1}
                onClick={() => moveCriterion(index, 1)}
              >
                <ArrowDown size={16} />
              </button>

              <button
                type="button"
                className="icon-button"
                aria-label={`Remove criterion ${index + 1}`}
                title="Remove criterion"
                disabled={saving || form.criteria.length === 1}
                onClick={() => removeCriterion(index)}
              >
                <Trash2 size={16} />
              </button>
            </div>
          </div>
        ))}

        <button
          type="button"
          className="inline-flex items-center gap-2 text-sm font-medium text-navy-900 disabled:opacity-50"
          disabled={saving}
          onClick={addCriterion}
        >
          <Plus size={16} />
          Add criterion
        </button>
      </fieldset>

      <div className="flex flex-wrap gap-3">
        <button
          type="submit"
          className="primary-button"
          disabled={saving}
        >
          {saving ? 'Saving…' : 'Save draft'}
        </button>

        <button
          type="button"
          onClick={onCancel}
          disabled={saving}
          className="rounded-lg border border-slate-300 px-4 py-2.5 text-sm font-medium text-slate-700 disabled:opacity-50"
        >
          Cancel
        </button>
      </div>
    </form>
  );
}

export default function LeadershipFormsPage() {
  const [forms, setForms] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [message, setMessage] = useState('');
  const [editor, setEditor] = useState(null);
  const [saving, setSaving] = useState(false);
  const [publishingId, setPublishingId] = useState(null);

  const load = useCallback(async () => {
    setLoading(true);
    setError('');

    try {
      const result = await getLeadershipForms();
      setForms(Array.isArray(result) ? result : []);
    } catch (err) {
      setError(err?.message || 'Unable to load leadership evaluation forms.');
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  async function openVersion(type, versionId, mode) {
    setError('');
    setMessage('');

    try {
      const version = await getLeadershipVersion(versionId);

      setEditor({
        type,
        versionId: mode === 'edit' ? versionId : null,
        form: {
          title: version.title || '',
          instructions: version.instructions || '',
          scaleMin: String(version.scaleMin ?? ''),
          scaleMax: String(version.scaleMax ?? ''),
          allowNa: Boolean(version.allowNa),
          criteria: Array.isArray(version.criteria)
            ? version.criteria.map((criterion) => ({
                sectionTitle: criterion.sectionTitle || '',
                text: criterion.text || '',
              }))
            : [{ sectionTitle: '', text: '' }],
        },
      });
    } catch (err) {
      setError(err?.message || 'Unable to load this form version.');
    }
  }

  async function save() {
    if (!editor || saving) return;

    const problem = validateForm(editor.form);

    if (problem) {
      setError(problem);
      return;
    }

    setSaving(true);
    setError('');
    setMessage('');

    try {
      const payload = toPayload(editor.form);

      if (editor.versionId) {
        await updateLeadershipVersion(editor.versionId, payload);
      } else {
        await createLeadershipVersion(editor.type, payload);
      }

      setEditor(null);
      setMessage('Draft saved successfully. Review it before publishing.');
      await load();
    } catch (err) {
      setError(err?.message || 'Unable to save the draft.');
    } finally {
      setSaving(false);
    }
  }

  async function publish(versionId) {
    if (publishingId !== null) return;

    const confirmed = await confirmAction(
      'Publish this version? New assignments will use it. Confirm that its criteria and scoring scale match the approved institutional form. Published versions cannot be edited.',
    );

    if (!confirmed) return;

    setPublishingId(versionId);
    setError('');
    setMessage('');

    try {
      await publishLeadershipVersion(versionId);
      setMessage('Leadership evaluation form version published successfully.');
      await load();
    } catch (err) {
      setError(err?.message || 'Unable to publish this form version.');
    } finally {
      setPublishingId(null);
    }
  }

  function startNewVersion(type) {
    setError('');
    setMessage('');
    setEditor({
      type,
      versionId: null,
      form: createEmptyForm(),
    });
  }

  function cancelEditor() {
    setEditor(null);
    setError('');
  }

  return (
    <div className="space-y-6">
      <header>
        <h1 className="text-2xl font-semibold text-slate-900">
          Leadership evaluation forms
        </h1>

        <p className="mt-1 max-w-4xl text-sm leading-6 text-slate-600">
          Manage separate evaluation forms for leadership roles. The Dean or
          Vice Dean evaluates the Department Head, while the Academic Affairs
          Vice President or Vice Director evaluates the Dean. Enter only
          criteria and scoring rules confirmed by the official institutional
          form.
        </p>
      </header>

      <ErrorBanner
        message={error}
        onRetry={!editor && !saving ? load : undefined}
      />

      <SuccessBanner message={message} />

      {loading && <LoadingBlock label="Loading leadership evaluation forms…" />}

      {!loading && !error && forms.length === 0 && !editor && (
        <div className="panel-card p-6">
          <h2 className="font-semibold text-slate-900">
            No leadership forms found
          </h2>
          <p className="mt-2 text-sm text-slate-600">
            Check your permissions and the leadership forms API. No form
            definitions have been returned.
          </p>
        </div>
      )}

      {editor && (
        <Editor
          editor={editor}
          saving={saving}
          onChange={(form) => setEditor((current) =>
            current ? { ...current, form } : current
          )}
          onSave={save}
          onCancel={cancelEditor}
        />
      )}

      {!loading &&
        forms.map((form) => {
          const type = getLeadershipType(form.type);

          return (
            <section key={form.type} className="panel-card">
              <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-200 p-5">
                <div>
                  <h2 className="text-base font-semibold text-slate-900">
                    {form.title || type.label}
                  </h2>

                  <p className="mt-1 text-sm text-slate-500">
                    {type.evaluator} → {type.evaluatee}
                  </p>
                </div>

                <button
                  type="button"
                  className="primary-button"
                  disabled={saving || publishingId !== null}
                  onClick={() => startNewVersion(form.type)}
                >
                  <Plus size={16} />
                  New version
                </button>
              </div>

              {!Array.isArray(form.versions) || form.versions.length === 0 ? (
                <p className="p-5 text-sm text-slate-500">
                  No versions exist yet. Create a draft and publish it after
                  verifying its official criteria and scoring scale.
                </p>
              ) : (
                <div className="overflow-x-auto">
                  <table className="min-w-full text-left text-sm">
                    <thead className="bg-slate-50 text-xs uppercase text-slate-500">
                      <tr>
                        <th scope="col" className="px-5 py-3">Version</th>
                        <th scope="col" className="px-5 py-3">Status</th>
                        <th scope="col" className="px-5 py-3">Scale</th>
                        <th scope="col" className="px-5 py-3">N/A</th>
                        <th scope="col" className="px-5 py-3">Criteria</th>
                        <th scope="col" className="px-5 py-3">Published</th>
                        <th scope="col" className="px-5 py-3 text-right">Actions</th>
                      </tr>
                    </thead>

                    <tbody className="divide-y divide-slate-100">
                      {form.versions.map((version) => (
                        <tr key={version.versionId}>
                          <td className="whitespace-nowrap px-5 py-3 font-medium">
                            v{version.versionNo}
                          </td>

                          <td className="px-5 py-3">
                            <StatusPill status={version.status} />
                          </td>

                          <td className="whitespace-nowrap px-5 py-3">
                            {version.scaleMin}–{version.scaleMax}
                          </td>

                          <td className="px-5 py-3">
                            {version.allowNa ? 'Allowed' : 'No'}
                          </td>

                          <td className="px-5 py-3">
                            {version.criteriaCount}
                          </td>

                          <td className="whitespace-nowrap px-5 py-3">
                            {formatDate(version.publishedAt)}
                          </td>

                          <td className="px-5 py-3">
                            <div className="flex justify-end gap-2">
                              {version.status === 'draft' && (
                                <>
                                  <button
                                    type="button"
                                    className="icon-button"
                                    aria-label={`Edit version ${version.versionNo}`}
                                    title="Edit draft"
                                    disabled={saving || publishingId !== null}
                                    onClick={() =>
                                      openVersion(form.type, version.versionId, 'edit')
                                    }
                                  >
                                    <Pencil size={16} />
                                  </button>

                                  <button
                                    type="button"
                                    className="icon-button"
                                    aria-label={`Publish version ${version.versionNo}`}
                                    title="Publish version"
                                    disabled={saving || publishingId !== null}
                                    onClick={() => publish(version.versionId)}
                                  >
                                    <Send size={16} />
                                  </button>
                                </>
                              )}

                              <button
                                type="button"
                                className="icon-button"
                                aria-label={`Copy version ${version.versionNo} into a new draft`}
                                title="Copy into new draft"
                                disabled={saving || publishingId !== null}
                                onClick={() =>
                                  openVersion(form.type, version.versionId, 'copy')
                                }
                              >
                                <Copy size={16} />
                              </button>
                            </div>
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              )}
            </section>
          );
        })}
    </div>
  );
}
